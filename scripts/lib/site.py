def sha256(path: Path) -> str:
    """Hex digest of a file, used to prove a published asset is unmodified."""
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


