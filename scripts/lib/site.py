def record_asset(path: Path) -> dict:
    """Manifest entry for a file already sitting where it is published.

    Used for the vendored chart libraries: they live in the site worktree by
    design, so copying them would mean copying a file onto itself.
    """
    return {
        "source": str(path),
        "published": path.name,
        "sha256": sha256(path),
        "bytes": path.stat().st_size,
    }


def copy_asset(src: Path, dest_dir: Path) -> dict:
    """Copy one asset into the site and return its provenance record."""
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / src.name
    shutil.copy2(src, dest)
    return {
        "source": str(src),
        "published": dest.name,
        "sha256": sha256(src),
        "bytes": src.stat().st_size,
    }


def es(value: float, decimals: int = 2) -> str:
    """Format a number the way Spanish writes it: comma as decimal separator.

    The site is Spanish-only, and a page that mixes "0,236" in hand-written
    prose with "0.2364" in an interpolated statistic reads as two documents
    stitched together. Every generated figure goes through here.
    """
    return f"{value:,.{decimals}f}".replace(",", "\u00a0").replace(".", ",")


def es_pct(fraction: float, decimals: int = 2) -> str:
    """Format a fraction as a Spanish-formatted percentage, without the sign."""
    return es(fraction * 100, decimals)


def escala_badge(escala: str) -> str:
    """Distintivo con la escala de observación y su unidad.

    Codifica algo verdadero y no decorativo: a qué unidad se refiere cada
    número de la página. Cruzar escalas sin decirlo es la forma más fácil de
    engañar a un lector, así que la escala viaja en el encabezado.
    """
    nombre, unidad = families_lib.ESCALA_LABEL[escala]
    clase = ESCALA_CLASE[escala]
    return f'<span class="escala {clase}">{nombre} &middot; {unidad}</span>'


